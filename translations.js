// Active language state
let currentLang = localStorage.getItem('kaamsetu_lang') || 'hi';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('kaamsetu_lang', lang);
}

function t(key) {
  const lang = TRANSLATIONS[currentLang];
  if (lang && lang[key] !== undefined) return lang[key];
  // fallback to Hindi
  const hi = TRANSLATIONS['hi'];
  return hi[key] || key;
}

function getDir() {
  const lang = TRANSLATIONS[currentLang];
  return lang ? (lang.dir || 'ltr') : 'ltr';
}

function applyDirection() {
  document.documentElement.dir = getDir();
  document.documentElement.lang = currentLang;
}

// Apply translations to all [data-i18n] elements
function applyTranslations() {
  applyDirection();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
}

